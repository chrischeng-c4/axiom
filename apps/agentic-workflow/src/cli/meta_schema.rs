pub fn schema(kind: Option<&str>) -> Result<Vec<&'static MetaDocSchema>> {
    match kind {
        None => Ok(META_SCHEMA_REGISTRY.iter().collect()),
        Some(kind) => {
            let normalized = kind.trim().to_ascii_lowercase().replace('_', "-");
            let Some(schema) = META_SCHEMA_REGISTRY
                .iter()
                .find(|schema| schema.kind == normalized)
            else {
                bail!(
                    "unknown META-doc kind `{kind}`; expected one of: {}",
                    META_SCHEMA_REGISTRY
                        .iter()
                        .map(|schema| schema.kind)
                        .collect::<Vec<_>>()
                        .join(", ")
                );
            };
            Ok(vec![schema])
        }
    }
}

pub fn validate_for_project(repository_root: &Path, project: &str) -> MetaValidationReport {
    let repository_root = meta_repository_root(repository_root);
    let rows = project_registry::load_project_config_rows(repository_root).unwrap_or_default();
    let row = rows.iter().find(|row| row.matches(project));
    let (repository_is_product, project_roots) = match row {
        Some(row) if row.path.trim().is_empty() || row.path == "." => (true, Vec::new()),
        Some(row) => (false, vec![PathBuf::from(&row.path)]),
        None => (false, Vec::new()),
    };
    validate(
        repository_root,
        repository_is_product,
        &project_roots,
        Some(project),
    )
}

fn meta_repository_root(start: &Path) -> &Path {
    let mut current = start;
    loop {
        if current.join("AGENTS.md").is_file()
            && current.join("CONTRIBUTING.md").is_file()
            && current.join("aw.toml").is_file()
        {
            return current;
        }
        let Some(parent) = current.parent() else {
            return start;
        };
        current = parent;
    }
}

pub fn validate(
    repository_root: &Path,
    repository_is_product: bool,
    project_roots: &[PathBuf],
    project: Option<&str>,
) -> MetaValidationReport {
    let mut findings =
        validate_meta_doc_layout(repository_root, repository_is_product, project_roots).findings;
    validate_structured_documents(
        repository_root,
        repository_is_product,
        project_roots,
        &mut findings,
    );
    let rules = validate_rules(repository_root, &mut findings);
    validate_rule_projections(repository_root, &rules, &mut findings);
    validate_runtime_adapters(repository_root, &mut findings);
    finish_report(findings, project)
}

fn finish_report(mut findings: Vec<MetaDocFinding>, project: Option<&str>) -> MetaValidationReport {
    findings.sort_by(|left, right| {
        (
            &left.severity,
            &left.axis,
            &left.path,
            &left.code,
            &left.message,
        )
            .cmp(&(
                &right.severity,
                &right.axis,
                &right.path,
                &right.code,
                &right.message,
            ))
    });
    findings.dedup();
    let blocker_count = findings
        .iter()
        .filter(|finding| finding.severity == MetaFindingSeverity::Blocker)
        .count();
    let drift_count = findings
        .iter()
        .filter(|finding| finding.severity == MetaFindingSeverity::Drift)
        .count();
    let advisory_count = findings
        .iter()
        .filter(|finding| finding.severity == MetaFindingSeverity::Advisory)
        .count();
    let mut axes = BTreeMap::new();
    for axis in [
        "documents",
        "schema",
        "ownership",
        "rules",
        "projections",
        "references",
        "placement",
        "coverage",
    ] {
        let axis_findings = findings
            .iter()
            .filter(|finding| finding.axis == axis)
            .collect::<Vec<_>>();
        axes.insert(
            axis.to_string(),
            MetaAxisSummary {
                blocker_count: axis_findings
                    .iter()
                    .filter(|finding| finding.severity == MetaFindingSeverity::Blocker)
                    .count(),
                drift_count: axis_findings
                    .iter()
                    .filter(|finding| finding.severity == MetaFindingSeverity::Drift)
                    .count(),
                advisory_count: axis_findings
                    .iter()
                    .filter(|finding| finding.severity == MetaFindingSeverity::Advisory)
                    .count(),
            },
        );
    }
    let next_command = findings
        .iter()
        .find(|finding| finding.severity != MetaFindingSeverity::Advisory)
        .map(|finding| remediation_command(finding, project));
    let scored = META_SCHEMA_REGISTRY.len() + 8;
    let failed = blocker_count.saturating_add(drift_count).min(scored);
    MetaValidationReport {
        schema_version: META_SCHEMA_VERSION,
        clean: blocker_count == 0 && drift_count == 0,
        blocker_count,
        drift_count,
        advisory_count,
        coverage_percent: (((scored - failed) * 100) / scored) as u8,
        axes,
        findings,
        next_command,
    }
}

fn remediation_command(finding: &MetaDocFinding, project: Option<&str>) -> String {
    let suffix = project
        .map(|project| format!(" --project {project}"))
        .unwrap_or_default();
    match finding.code.as_str() {
        "meta_doc_missing" => format!("aw meta init{suffix}"),
        "managed_block_stale"
        | "managed_block_missing"
        | "meta_rule_projection_missing"
        | "meta_rule_projection_stale"
        | "meta_rule_index_missing"
        | "meta_rule_index_stale"
        | "claude_adapter_stale" => format!("aw meta sync{suffix}"),
        _ => "aw meta schema".to_string(),
    }
}

fn validate_structured_documents(
    repository_root: &Path,
    repository_is_product: bool,
    project_roots: &[PathBuf],
    findings: &mut Vec<MetaDocFinding>,
) {
    validate_document_sections(
        repository_root,
        repository_root,
        "README.md",
        REPO_README_SECTIONS,
        false,
        findings,
    );
    validate_document_sections(
        repository_root,
        repository_root,
        "CONTRIBUTING.md",
        REPO_CONTRIBUTING_SECTIONS,
        false,
        findings,
    );
    validate_document_sections(
        repository_root,
        repository_root,
        "AGENTS.md",
        AGENT_BOOTSTRAP_SECTIONS,
        false,
        findings,
    );
    validate_document_sections(
        repository_root,
        repository_root,
        "CLAUDE.md",
        CLAUDE_ADAPTER_SECTIONS,
        false,
        findings,
    );
    if repository_is_product {
        validate_project_document_sections(repository_root, repository_root, findings);
    }
    for project_root in project_roots {
        let root = if project_root.is_absolute() {
            project_root.clone()
        } else {
            repository_root.join(project_root)
        };
        validate_project_document_sections(repository_root, &root, findings);
    }
}

