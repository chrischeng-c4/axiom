fn validate_document_sections(
    repository_root: &Path,
    document_root: &Path,
    filename: &str,
    sections: &[MetaSectionSchema],
    reject_unknown: bool,
    findings: &mut Vec<MetaDocFinding>,
) {
    let path = document_root.join(filename);
    let Ok(document) = fs::read_to_string(&path) else {
        return;
    };
    // README is human-first. The ownership matrix still requires its compact
    // link headings, but prose freedom and repository-as-product composition
    // mean duplicate/order enforcement belongs only to agent-first kinds.
    if filename == "README.md" {
        return;
    }
    let relative = display_path(repository_root, &path);
    let actual = document
        .lines()
        .filter(|line| line.starts_with("## "))
        .map(str::trim_end)
        .collect::<Vec<_>>();
    let mut prior = None;
    for section in sections {
        let indexes = actual
            .iter()
            .enumerate()
            .filter_map(|(index, heading)| (*heading == section.heading).then_some(index))
            .collect::<Vec<_>>();
        if indexes.len() > 1 {
            findings.push(finding(
                "meta_doc_section_duplicate",
                "schema",
                MetaFindingSeverity::Blocker,
                &relative,
                format!("`{}` appears {} times", section.heading, indexes.len()),
                "Inspect the live contract with `aw meta schema`, then keep exactly one section.",
            ));
        }
        if let Some(index) = indexes.first().copied() {
            if prior.is_some_and(|prior| index < prior) {
                findings.push(finding(
                    "meta_doc_section_out_of_order",
                    "schema",
                    MetaFindingSeverity::Blocker,
                    &relative,
                    format!("`{}` is outside the registry order", section.heading),
                    "Run `aw meta schema` and reorder the fixed sections.",
                ));
            }
            prior = Some(index);
        }
    }
    if reject_unknown {
        let allowed = sections
            .iter()
            .map(|section| section.heading)
            .collect::<BTreeSet<_>>();
        for heading in actual {
            if !allowed.contains(heading) {
                findings.push(finding(
                    "meta_doc_section_unknown",
                    "schema",
                    MetaFindingSeverity::Blocker,
                    &relative,
                    format!("unknown fixed section `{heading}`"),
                    "Run `aw meta schema` and move the content into a registered section.",
                ));
            }
        }
    }
}

fn validate_rules(repository_root: &Path, findings: &mut Vec<MetaDocFinding>) -> Vec<ParsedRule> {
    let rules_root = repository_root.join(".agents/rules");
    if !rules_root.is_dir() {
        findings.push(finding(
            "meta_rule_tree_missing",
            "rules",
            MetaFindingSeverity::Blocker,
            ".agents/rules",
            "canonical modular rule tree is missing",
            "Create one concern per `.agents/rules/<domain>/<concern>.md` using `aw meta schema agent-rule`.",
        ));
        return Vec::new();
    }
    let mut parsed = Vec::new();
    let mut ids = BTreeMap::<String, String>::new();
    for entry in WalkDir::new(&rules_root)
        .into_iter()
        .filter_map(std::result::Result::ok)
        .filter(|entry| entry.file_type().is_file())
    {
        let path = entry.path();
        if path.extension().and_then(|value| value.to_str()) != Some("md") {
            continue;
        }
        let relative = display_path(repository_root, path);
        let rule_relative = display_path(&rules_root, path);
        if Path::new(&rule_relative).components().count() < 2 {
            findings.push(finding(
                "meta_rule_semantic_path_invalid",
                "placement",
                MetaFindingSeverity::Blocker,
                &relative,
                "rule must live under a semantic domain directory",
                "Move the rule to `.agents/rules/<domain>/<concern>.md` and keep its id aligned with that path.",
            ));
        }
        let document = match fs::read_to_string(path) {
            Ok(document) => document,
            Err(error) => {
                findings.push(finding(
                    "meta_rule_unreadable",
                    "rules",
                    MetaFindingSeverity::Blocker,
                    &relative,
                    format!("cannot read canonical rule: {error}"),
                    "Repair the rule encoding or permissions, then rerun `aw meta check`.",
                ));
                continue;
            }
        };
        let Some((frontmatter, body)) = split_frontmatter(&document) else {
            findings.push(finding(
                "meta_rule_frontmatter_missing",
                "schema",
                MetaFindingSeverity::Blocker,
                &relative,
                "rule must start with YAML frontmatter",
                "Use the shape from `aw meta schema agent-rule`.",
            ));
            continue;
        };
        let frontmatter = match serde_yaml::from_str::<AgentRuleFrontmatter>(frontmatter) {
            Ok(frontmatter) => frontmatter,
            Err(error) => {
                findings.push(finding(
                    "meta_rule_frontmatter_invalid",
                    "schema",
                    MetaFindingSeverity::Blocker,
                    &relative,
                    format!("invalid rule frontmatter: {error}"),
                    "Use only fields and enum values reported by `aw meta schema agent-rule`.",
                ));
                continue;
            }
        };
        let expected_id = rule_relative
            .strip_suffix(".md")
            .unwrap_or(&rule_relative)
            .replace(['/', '\\'], ".");
        if frontmatter.id != expected_id {
            findings.push(finding(
                "meta_rule_id_path_mismatch",
                "ownership",
                MetaFindingSeverity::Blocker,
                &relative,
                format!(
                    "rule id `{}` must equal semantic path id `{expected_id}`",
                    frontmatter.id
                ),
                "Rename the file or id so `.agents/rules/<domain>/<concern>.md` maps to `<domain>.<concern>`.",
            ));
        }
        if let Some(first_path) = ids.insert(frontmatter.id.clone(), relative.clone()) {
            findings.push(finding(
                "meta_rule_id_duplicate",
                "ownership",
                MetaFindingSeverity::Blocker,
                &relative,
                format!(
                    "rule id `{}` is already owned by {first_path}",
                    frontmatter.id
                ),
                "Give each canonical rule one unique stable id.",
            ));
        }
        if frontmatter.targets.is_empty() {
            findings.push(finding(
                "meta_rule_targets_empty",
                "schema",
                MetaFindingSeverity::Blocker,
                &relative,
                "rule must name at least one runtime target",
                "Set `targets` to one or more of `claude`, `codex`, or `agy`.",
            ));
        }
        if frontmatter.activation == RuleActivation::Path && frontmatter.scope.is_empty() {
            findings.push(finding(
                "meta_rule_path_scope_missing",
                "schema",
                MetaFindingSeverity::Blocker,
                &relative,
                "path activation requires at least one scope glob",
                "Add one or more repository-relative globs to `scope`.",
            ));
        }
        for pattern in &frontmatter.scope {
            if pattern.starts_with('/') || pattern.contains("..") || Glob::new(pattern).is_err() {
                findings.push(finding(
                    "meta_rule_glob_invalid",
                    "schema",
                    MetaFindingSeverity::Blocker,
                    &relative,
                    format!("invalid repository-relative scope glob `{pattern}`"),
                    "Use a valid repository-relative glob without `/` prefix or `..` traversal.",
                ));
            }
        }
        validate_rule_body(&relative, body, findings);
        for reference in &frontmatter.required_references {
            if reference.starts_with("http://") || reference.starts_with("https://") {
                continue;
            }
            let reference_path = repository_root.join(reference);
            if !reference_path.exists() {
                findings.push(finding(
                    "meta_rule_reference_unresolved",
                    "references",
                    MetaFindingSeverity::Blocker,
                    &relative,
                    format!("required reference `{reference}` does not resolve"),
                    "Fix the repository-relative reference or remove it from `required_references`.",
                ));
            }
        }
        let title = body
            .lines()
            .find_map(|line| line.strip_prefix("# ").map(str::to_string))
            .unwrap_or_else(|| frontmatter.id.clone());
        parsed.push(ParsedRule {
            relative_path: rule_relative,
            title,
            body: body.to_string(),
            frontmatter,
        });
    }
    parsed.sort_by(|left, right| left.frontmatter.id.cmp(&right.frontmatter.id));
    if parsed.is_empty()
        && findings
            .iter()
            .all(|finding| finding.code != "meta_rule_tree_missing")
    {
        findings.push(finding(
            "meta_rule_tree_empty",
            "rules",
            MetaFindingSeverity::Blocker,
            ".agents/rules",
            "canonical rule tree contains no rule files",
            "Create one concern per semantic rule file using `aw meta schema agent-rule`.",
        ));
    }
    parsed
}

fn validate_rule_body(relative: &str, body: &str, findings: &mut Vec<MetaDocFinding>) {
    let headings = body
        .lines()
        .filter(|line| line.starts_with("## "))
        .map(str::trim_end)
        .collect::<Vec<_>>();
    let expected = RULE_SECTIONS
        .iter()
        .map(|section| section.heading)
        .collect::<Vec<_>>();
    for heading in &expected {
        let count = headings.iter().filter(|actual| *actual == heading).count();
        if count > 1 {
            findings.push(finding(
                "meta_rule_section_duplicate",
                "schema",
                MetaFindingSeverity::Blocker,
                relative,
                format!("rule section `{heading}` appears {count} times"),
                "Keep each fixed rule section exactly once.",
            ));
        }
    }
    for heading in &headings {
        if !expected.contains(heading) {
            findings.push(finding(
                "meta_rule_section_unknown",
                "schema",
                MetaFindingSeverity::Blocker,
                relative,
                format!("unknown rule section `{heading}`"),
                "Move the content into Intent, Rules, Verification, or References.",
            ));
        }
    }
    if headings != expected {
        findings.push(finding(
            "meta_rule_sections_invalid",
            "schema",
            MetaFindingSeverity::Blocker,
            relative,
            format!(
                "rule sections must be exactly `{}` in order",
                expected.join("`, `")
            ),
            "Rewrite the body to the fixed shape from `aw meta schema agent-rule`.",
        ));
    }
    if body.lines().any(|line| {
        let trimmed = line.trim_start();
        trimmed.starts_with("1. ") || trimmed.starts_with("Step 1")
    }) {
        findings.push(finding(
            "meta_rule_procedure_suspected",
            "rules",
            MetaFindingSeverity::Advisory,
            relative,
            "numbered procedure detected; multi-step playbooks normally belong in a human-invoked skill",
            "Keep declarative constraints here and move task procedure to a skill when it is independently invoked.",
        ));
    }
}

fn validate_rule_projections(
    repository_root: &Path,
    rules: &[ParsedRule],
    findings: &mut Vec<MetaDocFinding>,
) {
    let mut expected_paths = BTreeSet::new();
    for rule in rules {
        if rule.frontmatter.targets.contains(&RuleTarget::Claude) {
            let path = repository_root
                .join(".claude/rules")
                .join(&rule.relative_path);
            expected_paths.insert(path.clone());
            let relative = display_path(repository_root, &path);
            let expected = render_claude_projection(rule);
            match fs::read_to_string(&path) {
                Ok(actual) if actual == expected => {}
                Ok(_) => findings.push(finding(
                    "meta_rule_projection_stale",
                    "projections",
                    MetaFindingSeverity::Drift,
                    &relative,
                    format!(
                        "Claude rule projection for `{}` is stale",
                        rule.frontmatter.id
                    ),
                    "Run `aw meta sync` to regenerate runtime projections.",
                )),
                Err(_) => findings.push(finding(
                    "meta_rule_projection_missing",
                    "projections",
                    MetaFindingSeverity::Drift,
                    &relative,
                    format!(
                        "Claude rule projection for `{}` is missing",
                        rule.frontmatter.id
                    ),
                    "Run `aw meta sync` to generate runtime projections.",
                )),
            }
        }
    }
    let claude_root = repository_root.join(".claude/rules");
    if claude_root.is_dir() {
        for entry in WalkDir::new(&claude_root)
            .into_iter()
            .filter_map(std::result::Result::ok)
            .filter(|entry| entry.file_type().is_file())
        {
            let path = entry.path();
            if expected_paths.contains(path) {
                continue;
            }
            if fs::read_to_string(path)
                .ok()
                .is_some_and(|body| body.contains(RULE_PROJECTION_MARKER))
            {
                findings.push(finding(
                    "meta_rule_projection_orphan",
                    "projections",
                    MetaFindingSeverity::Drift,
                    &display_path(repository_root, path),
                    "generated Claude rule has no canonical source",
                    "Run `aw meta sync` to remove orphaned generated projections.",
                ));
            }
        }
    }
    let agents = repository_root.join("AGENTS.md");
    if let Ok(document) = fs::read_to_string(&agents) {
        let expected = render_rule_index(rules);
        match marker_body(&document, RULE_INDEX_START, RULE_INDEX_END) {
            Some(actual) if actual.trim() == expected.trim() => {}
            Some(_) => findings.push(finding(
                "meta_rule_index_stale",
                "projections",
                MetaFindingSeverity::Drift,
                "AGENTS.md",
                "generated canonical rule index is stale",
                "Run `aw meta sync` to refresh the Codex routing index.",
            )),
            None => findings.push(finding(
                "meta_rule_index_missing",
                "projections",
                MetaFindingSeverity::Drift,
                "AGENTS.md",
                "generated canonical rule index is missing",
                "Run `aw meta sync` to add the Codex routing index.",
            )),
        }
    }
}

fn validate_runtime_adapters(repository_root: &Path, findings: &mut Vec<MetaDocFinding>) {
    let claude = fs::read_to_string(repository_root.join("CLAUDE.md")).unwrap_or_default();
    if !claude.lines().any(|line| line.trim() == "@AGENTS.md") {
        findings.push(finding(
            "claude_adapter_stale",
            "projections",
            MetaFindingSeverity::Advisory,
            "CLAUDE.md",
            "Claude adapter does not yet import `@AGENTS.md`; shared guidance is still migration-era duplicated content",
            "Run `aw meta sync` after migrating shared reusable guidance into `.agents/rules`.",
        ));
    }
    let agents = fs::read_to_string(repository_root.join("AGENTS.md")).unwrap_or_default();
    if agents.lines().count() > 240 {
        findings.push(finding(
            "agent_bootstrap_large",
            "coverage",
            MetaFindingSeverity::Advisory,
            "AGENTS.md",
            "AGENTS bootstrap is large; reusable concerns should continue migrating into canonical rule files",
            "Move one coherent reusable concern at a time to `.agents/rules/<domain>/<concern>.md`.",
        ));
    }
}

pub fn sync_rule_projections(repository_root: &Path) -> Result<Vec<String>> {
    let mut changed = ensure_default_rule(repository_root)?;
    let mut validation_findings = Vec::new();
    let rules = validate_rules(repository_root, &mut validation_findings);
    if let Some(finding) = validation_findings
        .iter()
        .find(|finding| finding.severity == MetaFindingSeverity::Blocker)
    {
        bail!("{}: {}", finding.path, finding.message);
    }
    let mut expected_paths = BTreeSet::new();
    for rule in &rules {
        if !rule.frontmatter.targets.contains(&RuleTarget::Claude) {
            continue;
        }
        let path = repository_root
            .join(".claude/rules")
            .join(&rule.relative_path);
        expected_paths.insert(path.clone());
        let expected = render_claude_projection(rule);
        if fs::read_to_string(&path).ok().as_deref() == Some(expected.as_str()) {
            continue;
        }
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).with_context(|| {
                format!("create rule projection directory {}", parent.display())
            })?;
        }
        fs::write(&path, expected)
            .with_context(|| format!("write rule projection {}", path.display()))?;
        changed.push(display_path(repository_root, &path));
    }
    let claude_root = repository_root.join(".claude/rules");
    if claude_root.is_dir() {
        for entry in WalkDir::new(&claude_root)
            .into_iter()
            .filter_map(std::result::Result::ok)
            .filter(|entry| entry.file_type().is_file())
        {
            let path = entry.path();
            if expected_paths.contains(path) {
                continue;
            }
            if fs::read_to_string(path)
                .ok()
                .is_some_and(|body| body.contains(RULE_PROJECTION_MARKER))
            {
                fs::remove_file(path)
                    .with_context(|| format!("remove orphan projection {}", path.display()))?;
                changed.push(display_path(repository_root, path));
            }
        }
    }
    let agents_path = repository_root.join("AGENTS.md");
    if let Ok(agents) = fs::read_to_string(&agents_path) {
        let index = render_rule_index(&rules);
        let desired = upsert_marker_block(&agents, RULE_INDEX_START, RULE_INDEX_END, &index)?;
        if desired != agents {
            fs::write(&agents_path, desired).context("write AGENTS rule index")?;
            changed.push("AGENTS.md".to_string());
        }
    }
    changed.sort();
    changed.dedup();
    Ok(changed)
}

fn ensure_default_rule(repository_root: &Path) -> Result<Vec<String>> {
    let rules_root = repository_root.join(".agents/rules");
    let has_rule = rules_root.is_dir()
        && WalkDir::new(&rules_root)
            .into_iter()
            .filter_map(std::result::Result::ok)
            .any(|entry| {
                entry.file_type().is_file()
                    && entry.path().extension().and_then(|value| value.to_str()) == Some("md")
            });
    if has_rule {
        return Ok(Vec::new());
    }
    let path = rules_root.join("workflow/agentic-workflow.md");
    fs::create_dir_all(path.parent().expect("default rule parent"))
        .with_context(|| format!("create default rule directory {}", rules_root.display()))?;
    fs::write(&path, DEFAULT_AGENT_RULE)
        .with_context(|| format!("write default canonical rule {}", path.display()))?;
    Ok(vec![display_path(repository_root, &path)])
}

fn render_claude_projection(rule: &ParsedRule) -> String {
    let paths = if rule.frontmatter.activation == RuleActivation::Path {
        let values = rule
            .frontmatter
            .scope
            .iter()
            .map(|scope| format!("  - {scope:?}"))
            .collect::<Vec<_>>()
            .join("\n");
        format!("---\npaths:\n{values}\n---\n\n")
    } else {
        String::new()
    };
    format!(
        "{paths}{RULE_PROJECTION_MARKER}\n<!-- source: .agents/rules/{}; id: {} -->\n\n{}",
        rule.relative_path,
        rule.frontmatter.id,
        rule.body.trim_start()
    )
}

fn render_rule_index(rules: &[ParsedRule]) -> String {
    let mut out = String::from(
        "## Canonical Agent Rules\n\n\
         Reusable instructions live in `.agents/rules`; this generated index routes Codex by semantic path. \
         Claude projections live in `.claude/rules`; AGY consumes the canonical tree. \
         `.codex/rules` remains command-approval policy, never instruction content.\n\n\
         | Rule | Scope | Targets | Enforcement | Source |\n\
         |---|---|---|---|---|\n",
    );
    for rule in rules {
        let scope = if rule.frontmatter.scope.is_empty() {
            "always".to_string()
        } else {
            rule.frontmatter.scope.join("<br>")
        };
        let targets = rule
            .frontmatter
            .targets
            .iter()
            .map(|target| format!("{target:?}").to_ascii_lowercase())
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!(
            "| `{}` — {} | {} | {} | {:?} | [`.agents/rules/{}`](.agents/rules/{}) |\n",
            rule.frontmatter.id,
            rule.title,
            scope,
            targets,
            rule.frontmatter.enforcement,
            rule.relative_path,
            rule.relative_path,
        ));
    }
    out
}

fn split_frontmatter(document: &str) -> Option<(&str, &str)> {
    let rest = document.strip_prefix("---\n")?;
    let end = rest.find("\n---\n")?;
    Some((&rest[..end], &rest[end + 5..]))
}

fn marker_body<'a>(document: &'a str, start: &str, end: &str) -> Option<&'a str> {
    let start_index = document.find(start)? + start.len();
    let end_index = document[start_index..].find(end)? + start_index;
    Some(&document[start_index..end_index])
}

fn upsert_marker_block(document: &str, start: &str, end: &str, body: &str) -> Result<String> {
    let block = format!("{start}\n{}\n{end}", body.trim_end());
    match (document.find(start), document.find(end)) {
        (Some(start_index), Some(end_index)) if end_index >= start_index => {
            let end_index = end_index + end.len();
            Ok(format!(
                "{}{}{}",
                &document[..start_index],
                block,
                &document[end_index..]
            ))
        }
        (None, None) => {
            let separator = if document.ends_with("\n\n") {
                ""
            } else if document.ends_with('\n') {
                "\n"
            } else {
                "\n\n"
            };
            Ok(format!("{document}{separator}{block}\n"))
        }
        _ => bail!("unmatched META rule-index marker in AGENTS.md"),
    }
}

fn finding(
    code: &str,
    axis: &str,
    severity: MetaFindingSeverity,
    path: &str,
    message: impl Into<String>,
    remediation: impl Into<String>,
) -> MetaDocFinding {
    MetaDocFinding {
        code: code.to_string(),
        axis: axis.to_string(),
        severity,
        path: path.to_string(),
        message: message.into(),
        remediation: remediation.into(),
    }
}

fn display_path(root: &Path, path: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

