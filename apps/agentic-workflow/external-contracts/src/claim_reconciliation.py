"""Reconcile required capability claims with canonical Python EC cases.

The default mode is read-only. ``--write`` materializes ordinary, inspectable
Python modules plus a deterministic pyproject inventory block; independent EC
review and verification remain separate mandatory steps.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass
from pathlib import Path


EC_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = Path(__file__).resolve().parents[4]
PYPROJECT_PATH = EC_ROOT / "pyproject.toml"
CASE_ROOT = EC_ROOT / "src" / "cases"
BLOCK_START = "# aw:claim-reconciliation:start"
BLOCK_END = "# aw:claim-reconciliation:end"
GENERATED_MARKER = "# Generated by src/claim_reconciliation.py; semantic acceptance requires independent EC review."
CASE_ID_PREFIX = "claim-closure-"
EXPLICIT_GATE_OVERRIDES = {
    (
        "aw-core-client-model-workitem-first-artifact-lifecycle",
        "typed-agent-prompt-contract",
    ): (
        "cargo test -p agentic-workflow --lib "
        "cli::llm::tests::prompt_topic_public_renderer_pins_closed_language "
        "-- --exact --nocapture",
    ),
    (
        "td-cb-lifecycle-automation",
        "fixture-platform-config-rot",
    ): (
        "cargo test -p agentic-workflow --test cli_tests chain_liveness -- --nocapture",
        "cargo test -p agentic-workflow --test cli_tests fixture_loop -- --nocapture",
        "cargo test -p agentic-workflow --test self_hosting_runner_policy_cli_test "
        "self_hosting_health_reports_policy_and_never_points_back_to_root_runner "
        "-- --nocapture",
    ),
}
EXECUTABLE_GATE_PREFIXES = ("cargo test ", "python3 ")


@dataclass(frozen=True)
class ClaimCase:
    case_id: str
    capability_id: str
    claim_id: str
    user_story: str
    claim_oracle: str
    commands: tuple[str, ...]
    reference_tokens: tuple[str, ...]

    @property
    def artifact_id(self) -> str:
        return f"artifact:agentic-workflow/{self.case_id}"

    @property
    def test_path(self) -> str:
        return f"src/cases/{self.case_id}.py"

    @property
    def evidence_path(self) -> str:
        return f"evidence/{self.case_id}.json"

    @property
    def runner_command(self) -> str:
        return (
            "python3 apps/agentic-workflow/external-contracts/src/runner.py "
            f"--case {self.case_id} -- python3 "
            "apps/agentic-workflow/external-contracts/src/claim_gate.py "
            f"--case {self.case_id}"
        )

    @property
    def gate_command(self) -> str:
        return (
            "python3 apps/agentic-workflow/external-contracts/src/claim_gate.py "
            f"--case {self.case_id}"
        )


@dataclass(frozen=True)
class ReconciliationState:
    expected_modules: dict[Path, str]
    expected_pyproject: str
    stale_modules: tuple[Path, ...]
    drifted_modules: tuple[str, ...]
    pyproject_drifted: bool


def _arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--write",
        action="store_true",
        help="materialize the deterministic inventory block and case modules",
    )
    parser.add_argument(
        "--verify",
        action="store_true",
        help="run every reconciled case through the canonical evidence runner",
    )
    parser.add_argument(
        "--jobs",
        type=int,
        default=4,
        help="maximum concurrent evidence runners used by --verify",
    )
    parser.add_argument(
        "--aw-bin",
        default=os.environ.get("AW_BIN", str(REPOSITORY_ROOT / "target/debug/aw")),
        help="AW binary used for the canonical capability report",
    )
    return parser.parse_args()


def _capability_report(aw_bin: str) -> dict[str, object]:
    completed = subprocess.run(
        [
            aw_bin,
            "capability",
            "report",
            "--project",
            "agentic-workflow",
            "--skip-issue-inventory",
        ],
        cwd=REPOSITORY_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise RuntimeError(
            "canonical capability report failed:\n"
            f"{completed.stdout}\n{completed.stderr}"
        )
    return json.loads(completed.stdout)


def _generated_case_ids(pyproject: str) -> set[str]:
    block = _existing_generated_block(pyproject)
    return set(re.findall(r'^id = "([^"]+)"$', block, flags=re.MULTILINE))


def _validate_catalog_and_python_td_refs(report: dict[str, object]) -> None:
    blockers = report.get("blockers", [])
    invalid_work_roots = [
        str(blocker)
        for blocker in blockers
        if isinstance(blocker, str) and "work root" in blocker and "invalid Kind" in blocker
    ]
    if invalid_work_roots:
        raise RuntimeError(
            "capability catalog contains unsupported Work Root kinds:\n"
            + "\n".join(invalid_work_roots)
        )

    registered_claims: set[tuple[str, str]] = set()
    capabilities = report.get("capabilities")
    if not isinstance(capabilities, list):
        raise RuntimeError("capability report has no capability contracts")
    for capability in capabilities:
        if not isinstance(capability, dict):
            continue
        capability_id = str(capability.get("id", ""))
        claims = capability.get("claims", [])
        if not isinstance(claims, list):
            continue
        registered_claims.update(
            (capability_id, str(claim.get("id", "")))
            for claim in claims
            if isinstance(claim, dict)
        )

    python_artifact = report.get("python_artifact")
    if not isinstance(python_artifact, dict):
        raise RuntimeError("capability report has no Python artifact projection")
    module_ids = python_artifact.get("td_module_ids", [])
    if not isinstance(module_ids, list):
        raise RuntimeError("capability report has no Python TD module inventory")
    unresolved = []
    for module_id in module_ids:
        match = re.fullmatch(r"artifact:([^/]+)/([^/]+)", str(module_id))
        if match is None or match.groups() not in registered_claims:
            unresolved.append(str(module_id))
    if unresolved:
        raise RuntimeError(
            "canonical Python TD artifact ids do not resolve to registered "
            "capability claims: " + ", ".join(sorted(unresolved))
        )


def _existing_generated_block(pyproject: str) -> str:
    if BLOCK_START not in pyproject and BLOCK_END not in pyproject:
        return ""
    if pyproject.count(BLOCK_START) != 1 or pyproject.count(BLOCK_END) != 1:
        raise RuntimeError("claim reconciliation markers must appear exactly once")
    start = pyproject.index(BLOCK_START)
    end = pyproject.index(BLOCK_END, start) + len(BLOCK_END)
    return pyproject[start:end]


def _claims_to_generate(
    report: dict[str, object], generated_ids: set[str]
) -> list[ClaimCase]:
    python_artifact = report.get("python_artifact")
    if not isinstance(python_artifact, dict):
        raise RuntimeError("capability report has no Python artifact projection")
    cases = python_artifact.get("cases")
    if not isinstance(cases, list):
        raise RuntimeError("capability report has no Python EC case inventory")
    baseline_pairs = {
        (case["capability_id"], case["use_case_id"])
        for case in cases
        if isinstance(case, dict) and case.get("id") not in generated_ids
    }

    desired: list[ClaimCase] = []
    capabilities = report.get("capabilities")
    if not isinstance(capabilities, list):
        raise RuntimeError("capability report has no capability contracts")
    for capability in capabilities:
        if not isinstance(capability, dict):
            continue
        capability_id = str(capability.get("id", ""))
        claims = capability.get("claims", [])
        if not isinstance(claims, list):
            continue
        for claim in claims:
            if not isinstance(claim, dict) or not claim.get("required_for_verified"):
                continue
            claim_id = str(claim.get("id", ""))
            if (capability_id, claim_id) in baseline_pairs:
                continue
            gates = claim.get("gates", [])
            gate_tokens = tuple(
                str(gate.get("command", "")).strip()
                for gate in gates
                if isinstance(gate, dict) and str(gate.get("command", "")).strip()
            )
            commands = tuple(
                dict.fromkeys(
                    token
                    for token in gate_tokens
                    if token.startswith(EXECUTABLE_GATE_PREFIXES)
                )
            )
            if not commands:
                commands = EXPLICIT_GATE_OVERRIDES.get(
                    (capability_id, claim_id), ()
                )
            if not commands:
                raise RuntimeError(
                    f"required claim {capability_id}:{claim_id} has no supported "
                    "machine gate or explicit reviewed aggregate mapping"
                )
            claim_oracle = str(claim.get("oracle", "")).strip()
            if not claim_oracle:
                raise RuntimeError(
                    f"required claim {capability_id}:{claim_id} has no concrete oracle"
                )
            desired.append(
                ClaimCase(
                    case_id=f"{CASE_ID_PREFIX}{capability_id}-{claim_id}",
                    capability_id=capability_id,
                    claim_id=claim_id,
                    user_story=str(claim.get("user_story", claim_id)),
                    claim_oracle=claim_oracle,
                    commands=commands,
                    reference_tokens=tuple(
                        token for token in gate_tokens if token not in commands
                    ),
                )
            )
    desired.sort(key=lambda case: case.case_id)
    return desired


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _render_inventory_block(cases: list[ClaimCase]) -> str:
    blocks = [BLOCK_START]
    for case in cases:
        blocks.extend(
            [
                "",
                "[[tool.aw.python-ec.cases]]",
                f"id = {_toml_string(case.case_id)}",
                f"artifact_id = {_toml_string(case.artifact_id)}",
                f"capability_id = {_toml_string(case.capability_id)}",
                f"use_case_id = {_toml_string(case.claim_id)}",
                'dimension = "behavior"',
                'applicability = "td"',
                f"test_path = {_toml_string(case.test_path)}",
                f"promise = {_toml_string(f'{case.user_story}: {case.claim_oracle}')}",
                f"oracle = {_toml_string(f'Every executable gate declared for {case.capability_id}:{case.claim_id} must run, exit zero, and every cargo test gate must execute at least one test. Gates: {'; '.join(case.commands)}')}",
                'target = "rust"',
                f"command = {_toml_string(case.runner_command)}",
                f"evidence_paths = [{_toml_string(case.evidence_path)}]",
            ]
        )
    blocks.extend(["", BLOCK_END])
    return "\n".join(blocks)


def _render_module(case: ClaimCase) -> str:
    assertions = (
        f"Required outcome for {case.capability_id}:{case.claim_id}: "
        f"{case.claim_oracle}",
        "Every declared executable gate runs successfully; cargo test selectors "
        "must execute at least one test.",
    )
    return (
        '"""Generated ordinary Python EC declaration for one required capability claim."""\n'
        "\n"
        f"{GENERATED_MARKER}\n"
        f"CASE_ID = {case.case_id!r}\n"
        f"CAPABILITY_ID = {case.capability_id!r}\n"
        f"USE_CASE_ID = {case.claim_id!r}\n"
        "DIMENSION = 'behavior'\n"
        f"TARGET_COMMAND = {case.gate_command!r}\n"
        f"TARGET_COMMANDS = {case.commands!r}\n"
        f"REFERENCE_TOKENS = {case.reference_tokens!r}\n"
        f"CLAIM_ORACLE = {case.claim_oracle!r}\n"
        f"ASSERTIONS = {assertions!r}\n"
    )


def _replace_inventory_block(pyproject: str, rendered: str) -> str:
    existing = _existing_generated_block(pyproject)
    if existing:
        return pyproject.replace(existing, rendered)
    return pyproject.rstrip() + "\n\n" + rendered + "\n"


def _owned_module_paths() -> set[Path]:
    return {
        path
        for path in CASE_ROOT.glob(f"{CASE_ID_PREFIX}*.py")
        if path.read_text(encoding="utf-8").splitlines()[2:3] == [GENERATED_MARKER]
    }


def _write_if_changed(path: Path, content: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(path)
    return True


def _reconciliation_state(
    cases: list[ClaimCase], pyproject: str
) -> ReconciliationState:
    expected_modules = {
        CASE_ROOT / f"{case.case_id}.py": _render_module(case) for case in cases
    }
    expected_pyproject = _replace_inventory_block(
        pyproject, _render_inventory_block(cases)
    )
    stale_modules = tuple(sorted(_owned_module_paths() - expected_modules.keys()))
    drifted_modules = tuple(
        sorted(
            str(path.relative_to(REPOSITORY_ROOT))
            for path, content in expected_modules.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        )
    )
    return ReconciliationState(
        expected_modules=expected_modules,
        expected_pyproject=expected_pyproject,
        stale_modules=stale_modules,
        drifted_modules=drifted_modules,
        pyproject_drifted=expected_pyproject != pyproject,
    )


def _verify_case(case: ClaimCase) -> tuple[str, int, str]:
    completed = subprocess.run(
        [
            sys.executable,
            str(EC_ROOT / "src" / "runner.py"),
            "--case",
            case.case_id,
            "--",
            *shlex.split(case.gate_command),
        ],
        cwd=REPOSITORY_ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    diagnostics = (completed.stdout + completed.stderr)[-4000:]
    return case.case_id, completed.returncode, diagnostics


def _verify_cases(cases: list[ClaimCase], jobs: int) -> int:
    if jobs < 1:
        raise RuntimeError("--jobs must be at least 1")
    failures: list[dict[str, object]] = []
    with ThreadPoolExecutor(max_workers=jobs) as executor:
        futures = {executor.submit(_verify_case, case): case.case_id for case in cases}
        for future in as_completed(futures):
            case_id, returncode, diagnostics = future.result()
            if returncode != 0:
                failures.append(
                    {
                        "case_id": case_id,
                        "returncode": returncode,
                        "diagnostics": diagnostics,
                    }
                )
    failures.sort(key=lambda failure: str(failure["case_id"]))
    result = {
        "schema_version": "aw.python-ec.claim-reconciliation.verify.v1",
        "status": "passed" if not failures else "failed",
        "case_count": len(cases),
        "passed_count": len(cases) - len(failures),
        "failed_count": len(failures),
        "failures": failures,
    }
    print(json.dumps(result, sort_keys=True))
    return 0 if not failures else 1


def main() -> int:
    args = _arguments()
    if args.write and args.verify:
        raise RuntimeError("--write and --verify are separate explicit phases")
    pyproject = PYPROJECT_PATH.read_text(encoding="utf-8")
    generated_ids = _generated_case_ids(pyproject)
    report = _capability_report(args.aw_bin)
    _validate_catalog_and_python_td_refs(report)
    cases = _claims_to_generate(report, generated_ids)
    state = _reconciliation_state(cases, pyproject)

    if args.verify:
        if (
            state.pyproject_drifted
            or state.drifted_modules
            or state.stale_modules
        ):
            raise RuntimeError(
                "claim reconciliation is drifted; run the emitted --write remediation first"
            )
        return _verify_cases(cases, args.jobs)

    if args.write:
        changed = _write_if_changed(PYPROJECT_PATH, state.expected_pyproject)
        for path, content in state.expected_modules.items():
            changed = _write_if_changed(path, content) or changed
        for path in state.stale_modules:
            path.unlink()
            changed = True
        result = {
            "schema_version": "aw.python-ec.claim-reconciliation.v1",
            "status": "written" if changed else "clean",
            "required_claim_case_count": len(cases),
            "changed": changed,
        }
        print(json.dumps(result, sort_keys=True))
        return 0

    clean = (
        not state.pyproject_drifted
        and not state.drifted_modules
        and not state.stale_modules
    )
    result = {
        "schema_version": "aw.python-ec.claim-reconciliation.v1",
        "status": "clean" if clean else "drifted",
        "required_claim_case_count": len(cases),
        "pyproject_drifted": state.pyproject_drifted,
        "drifted_modules": state.drifted_modules,
        "stale_modules": [
            str(path.relative_to(REPOSITORY_ROOT)) for path in state.stale_modules
        ],
        "next": None
        if clean
        else "python3 apps/agentic-workflow/external-contracts/src/claim_reconciliation.py --write",
    }
    print(json.dumps(result, sort_keys=True))
    return 0 if clean else 1


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, RuntimeError, json.JSONDecodeError) as error:
        print(f"claim reconciliation failed: {error}", file=sys.stderr)
        raise SystemExit(2)
