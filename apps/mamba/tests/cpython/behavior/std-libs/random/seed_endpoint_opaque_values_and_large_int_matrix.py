def raw_stream(rng):
    return tuple(rng.getrandbits(64) for _ in range(8))


def make_generator(entered):
    entered.append(True)
    yield 17
    yield 19


def make_bad_values():
    entered = []
    return [
        ("object", object(), None),
        ("range", range(3), None),
        ("iterator", iter((17, 19)), "iterator"),
        ("generator", make_generator(entered), entered),
        ("live", random.Random(97), "live"),
    ]


def reject(label, invoke, value):
    try:
        invoke(value)
    except TypeError:
        return
    raise AssertionError((label, "accepted"))


def assert_unconsumed(label, value, marker):
    if marker == "iterator":
        assert next(value) == 17, label
        assert next(value) == 19, label
    elif marker == "live":
        assert raw_stream(value) == LIVE_97, label
    elif isinstance(marker, list):
        assert not marker, (label, "generator entered")
        assert next(value) == 17, label
        assert next(value) == 19, label


def check_module_seed():
    for name, value, marker in make_bad_values():
        random.seed(2468)
        random.seed(2468)
        reject("module:" + name, random.seed, value)
        assert raw_stream(random) == BASELINE, "module:" + name
        assert_unconsumed("module:" + name, value, marker)


def check_method_seed(cls, label):
    for name, value, marker in make_bad_values():
        rng = cls(2468)
        reject(label + ":" + name, rng.seed, value)
        assert raw_stream(rng) == BASELINE, label + ":" + name
        assert_unconsumed(label + ":" + name, value, marker)


def check_constructor(cls, label):
    for name, value, marker in make_bad_values():
        reject(label + ":" + name, cls, value)
        assert_unconsumed(label + ":" + name, value, marker)


def fresh_seed(label, seed):
    if label == "bytearray":
        return bytearray(b"seed")
    return seed


def check_none_acceptance():
    random.seed(None)
    random.Random(None)
    rng = random.Random()
    rng.seed(None)
    DerivedRandom(None)
    derived = DerivedRandom()
    derived.seed(None)


def check_positive_row(label, seed, expected):
    random.seed(fresh_seed(label, seed))
    assert raw_stream(random) == expected, label + ":module"
    assert raw_stream(random.Random(fresh_seed(label, seed))) == expected, label + ":Random"
    rng = random.Random()
    rng.seed(fresh_seed(label, seed))
    assert raw_stream(rng) == expected, label + ":rng"
    assert raw_stream(DerivedRandom(fresh_seed(label, seed))) == expected, label + ":DerivedRandom"
    derived = DerivedRandom()
    derived.seed(fresh_seed(label, seed))
    assert raw_stream(derived) == expected, label + ":DerivedRandom.seed"


